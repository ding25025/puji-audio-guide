#!/usr/bin/env bash
# 產生四個展區的語音檔（需先執行：pip install edge-tts）
# 用法：bash make-audio.sh
set -e

VOICE="zh-TW-HsiaoChenNeural"   # 女聲。男聲改成 zh-TW-YunJheNeural
RATE="-8%"                       # 稍微放慢，導覽聽起來比較清楚

mkdir -p txt

cat > txt/1.txt <<'EOF'
歡迎來到《小護法養成記》的第一站，啟蒙區。
在孩子心中，精舍是個安全又好玩的地方。剛接觸精舍的時候，我們用豐富多元的學習內容，還有溫暖的環境氛圍來引導他們。
除了固定的禪修班，在節慶的時候，我們還會舉辦兒童生日法會、大專密室逃脫等等的活動，讓孩子覺得精舍好酷、好想來。這正是佛法「先以欲鉤牽，後令入佛智」的慈悲智慧。
展板上留著孩子們的回饋，這些心聲，就是精舍給他們最真實的感受。
EOF

cat > txt/2.txt <<'EOF'
這裡是第二站，歷練區。
隨著孩子慢慢長大，光是好玩已經不夠了，他們開始渴望被認同。
這時候，精舍給他們有興趣的執事，還有同儕的陪伴，開啟了心燈、梵唄、司儀等等的發心平台。我們用「信任與容錯」的道風，給孩子們領執事、修善法的機會。
展板上這兩則漫畫，可不是捏造的，而是他們在錯誤中成長的真實故事。我們還把它做成了一本漫畫書，歡迎您到漫畫區自由翻閱。
EOF

cat > txt/3.txt <<'EOF'
這裡是第三站，叛逆區。
「別再問了，我沒有要去啦！」這句話，家裡有青少年的人，聽起來是不是特別熟悉？
到了青年期，面對課業或是人際挫折，孩子常常會不想來精舍。這時候，精舍的法寶就是溫暖與陪伴。不勉強、不放棄，靜心等候下一個因緣。父母的堅持，正是護念青年在精舍成長最堅強的力量。
這一區有一座「時光電話亭」，護念導航讓您不迷航，只要拿起電話，就能聽到護念者分享護念心法的九大招。
旁邊還有「煩惱法門對對碰」，這些問題都是青年最常遇到的煩惱，歡迎您動手翻開答案，看看老和尚教我們怎麼用智慧解題。
EOF

cat > txt/4.txt <<'EOF'
這裡是最後一站，成長區。
度過了叛逆期的風雨，孩子終於成熟了。
調研中我們注意到，很多青年在社會歷練一圈之後，回過頭才明白：原來，精舍才是最溫暖的家。因為感恩，他們從「被護念的人」，轉變成「想護念他人」的人。
展板上這張善循環圖：精舍用五大核心培養青年，讓佛法紮根；青年透過學佛和承擔執事來修養品格，進而護持道場、擴展視野。這就是一個從「被護念者」到「護念他人」的善循環。
在住持法師的帶領下，護念者以身作則，成為青年最好的榜樣。這種典範的力量，正是青年願意全心護持的核心關鍵。
佛法傳承需要向下扎根，小護法的養成，要一代接一代。護念一顆菩提種子，就能成就未來護法因緣。
感謝您的聆聽，阿彌陀佛。
EOF

# 發音修正：edge-tts 不支援 SSML，只能用同音字引導合成引擎讀出正確的音。
# txt/ 保留原文（給人看），實際送去合成的是 tts/ 裡替換過的版本。
#   精舍 → 精社   讓「舍」唸四聲 shè，而不是三聲 shě
#   梵唄 → 梵拜   讓「唄」唸 bài，而不是輕聲的 bei
#   道場 → 道廠   讓「場」唸三聲 chǎng，而不是二聲 cháng
mkdir -p tts

for i in 1 2 3 4; do
  echo "產生 audio$i.mp3 ..."
  sed -e 's/精舍/精社/g' -e 's/梵唄/梵拜/g' -e 's/道場/道廠/g' "txt/$i.txt" > "tts/$i.txt"
  edge-tts --voice "$VOICE" --rate="$RATE" \
           --file "tts/$i.txt" --write-media "audio$i.mp3"
done

echo
echo "完成。請把 index.html 和 audio1~4.mp3 放在同一個資料夾上傳。"
ls -lh audio*.mp3
